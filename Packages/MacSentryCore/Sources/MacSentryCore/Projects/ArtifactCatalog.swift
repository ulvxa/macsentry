import Darwin
import Foundation

public enum Ecosystem: String, Sendable, Codable, CaseIterable, Comparable {
    case node, python, rust, gradle, unity, apple, flutter, generic, arduino

    public static func < (lhs: Ecosystem, rhs: Ecosystem) -> Bool {
        lhs.rawValue < rhs.rawValue
    }

    public var regenerationHint: String {
        switch self {
        case .node:
            "Reinstalled by `npm install` (or `yarn` / `pnpm install`) and rebuilt by the project's dev or build script."
        case .python:
            "Recreate the environment with `python -m venv .venv` and `pip install -r requirements.txt`; caches rebuild on the next run."
        case .rust:
            "Rebuilt by `cargo build`."
        case .gradle:
            "Rebuilt by `./gradlew build` or the next Android Studio sync."
        case .unity:
            "Unity reimports all assets the next time the project is opened, which can take a long time on big projects."
        case .apple:
            "Rebuilt by Xcode or `swift build`; Pods are restored with `pod install`."
        case .flutter:
            "Restored by `flutter pub get` and rebuilt by `flutter build`."
        case .generic:
            "Build output regenerated by the project's build script. Check it is not committed or deployed output first."
        case .arduino:
            "Rebuilt by the Arduino IDE or `arduino-cli compile`."
        }
    }
}

public enum ArtifactMarker: Sendable, Equatable {
    case sibling([String])
    case contains(String)
    case rootFile(String)
    case none
}

public struct ArtifactRule: Sendable, Equatable {
    public let ecosystem: Ecosystem
    public let folder: String
    public let marker: ArtifactMarker
    public let tier: Tier

    public init(ecosystem: Ecosystem, folder: String, marker: ArtifactMarker, tier: Tier) {
        self.ecosystem = ecosystem
        self.folder = folder
        self.marker = marker
        self.tier = tier
    }

    public var ruleID: String {
        "graveyard.\(ecosystem.rawValue).\(folder)"
    }

    var components: [String] {
        folder.split(separator: "/").map(String.init)
    }

    var name: String {
        components.last ?? folder
    }

    var requiresMarker: Bool {
        marker != .none
    }
}

public struct ArtifactMatch: Sendable, Equatable {
    public let rule: ArtifactRule
    public let url: URL
    public let markerRoot: URL

    public init(rule: ArtifactRule, url: URL, markerRoot: URL) {
        self.rule = rule
        self.url = url
        self.markerRoot = markerRoot
    }
}

public struct ProjectMarker: Sendable, Equatable {
    public var hasGit: Bool
    public var ecosystems: Set<Ecosystem>

    public init(hasGit: Bool, ecosystems: Set<Ecosystem>) {
        self.hasGit = hasGit
        self.ecosystems = ecosystems
    }
}

public struct ArtifactCatalog: Sendable, Equatable {
    public let rules: [ArtifactRule]

    public init(rules: [ArtifactRule]) {
        self.rules = rules
    }

    public static let manifests: [(pattern: String, ecosystem: Ecosystem)] = [
        ("package.json", .node),
        ("Cargo.toml", .rust),
        ("pyproject.toml", .python),
        ("settings.gradle*", .gradle),
        ("Package.swift", .apple),
    ]

    public static let unityVersionFile = "ProjectSettings/ProjectVersion.txt"

    public static let `default`: ArtifactCatalog = {
        let packageJSON = ArtifactMarker.sibling(["package.json"])
        let gradle = ArtifactMarker.sibling(["build.gradle*", "settings.gradle*"])
        let apple = ArtifactMarker.sibling(["*.xcodeproj", "Package.swift"])
        let unity = ArtifactMarker.rootFile(unityVersionFile)
        let venv = ArtifactMarker.contains("pyvenv.cfg")
        var rules: [ArtifactRule] = [ArtifactRule(ecosystem: .node, folder: "node_modules", marker: packageJSON, tier: .green)]
        rules += [".next", ".nuxt", ".turbo", ".parcel-cache", ".svelte-kit", ".angular/cache"]
            .map { ArtifactRule(ecosystem: .node, folder: $0, marker: packageJSON, tier: .green) }
        rules += [".venv", "venv", "env"].map { ArtifactRule(ecosystem: .python, folder: $0, marker: venv, tier: .yellow) }
        rules += ["__pycache__", ".pytest_cache", ".mypy_cache", ".ruff_cache", ".tox"]
            .map { ArtifactRule(ecosystem: .python, folder: $0, marker: .none, tier: .green) }
        rules.append(ArtifactRule(ecosystem: .rust, folder: "target", marker: .sibling(["Cargo.toml"]), tier: .green))
        rules += ["build", ".gradle"].map { ArtifactRule(ecosystem: .gradle, folder: $0, marker: gradle, tier: .green) }
        rules += ["Library", "Temp", "Obj", "Logs"].map { ArtifactRule(ecosystem: .unity, folder: $0, marker: unity, tier: .yellow) }
        rules += ["DerivedData", ".build"].map { ArtifactRule(ecosystem: .apple, folder: $0, marker: apple, tier: .green) }
        rules.append(ArtifactRule(ecosystem: .apple, folder: "Pods", marker: .sibling(["Podfile"]), tier: .yellow))
        rules += [".dart_tool", "build"].map { ArtifactRule(
            ecosystem: .flutter,
            folder: $0,
            marker: .sibling(["pubspec.yaml"]),
            tier: .green,
        ) }
        rules += ["dist", "out"].map { ArtifactRule(ecosystem: .generic, folder: $0, marker: packageJSON, tier: .yellow) }
        rules.append(ArtifactRule(ecosystem: .arduino, folder: "build", marker: .sibling(["*.ino"]), tier: .green))
        return ArtifactCatalog(rules: rules)
    }()

    public var folderNames: Set<String> {
        Set(rules.map(\.name))
    }

    public func rules(named name: String) -> [ArtifactRule] {
        rules.filter { $0.name == name }
    }

    static func matches(_ pattern: String, _ name: String) -> Bool {
        fnmatch(pattern, name, 0) == 0
    }

    static func containsMatch(for patterns: [String], in entries: [String]) -> Bool {
        patterns.contains { pattern in entries.contains { matches(pattern, $0) } }
    }
}

public extension Candidate {
    var regenerationHint: String? {
        let parts = ruleID.split(separator: ".", maxSplits: 2)
        guard parts.count == 3, parts[0] == "graveyard" else { return nil }
        return Ecosystem(rawValue: String(parts[1]))?.regenerationHint
    }
}
